import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ baseURL: 'http://localhost:3001', viewport: { width: 1440, height: 900 } })
page.on('console', msg => console.log('console', msg.type(), msg.text()))
page.on('pageerror', err => console.log('pageerror', err.message))
await page.addInitScript(() => window.localStorage.setItem('slatecamp_sidebar_expanded', 'false'))
await page.goto('/dashboard', { waitUntil: 'load' })
await page.waitForTimeout(5000)
const sidebar = page.getByRole('navigation', { name: 'Main navigation' })
const button = page.getByRole('button', { name: 'Expand sidebar' })
console.log('hydrated?', await page.evaluate(() => !!document.querySelector('[data-nextjs-router-announcer]')))
console.log('box before', await sidebar.boundingBox(), await button.boundingBox())
console.log('label before', await button.getAttribute('aria-label'), await page.evaluate(() => localStorage.getItem('slatecamp_sidebar_expanded')))
await button.click({ force: true })
await page.waitForTimeout(1000)
console.log('box after', await sidebar.boundingBox())
console.log('label after', await button.getAttribute('aria-label'), await page.evaluate(() => localStorage.getItem('slatecamp_sidebar_expanded')))
await browser.close()
