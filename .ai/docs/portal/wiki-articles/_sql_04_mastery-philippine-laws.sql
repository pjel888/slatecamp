## The Building Codes Chain: From National to Local

The building regulatory framework layers from national legislation down to local enforcement.

**PD 1096 → Implementing Rules (DPWH) → Local Zoning Ordinances (LGU via RA 7160) → Building Permit (OBO)**

PD 1096 establishes the national minimum standards. Local zoning ordinances — enacted by LGUs under RA 7160 authority — can impose additional restrictions (tighter setbacks, lower height limits, use restrictions in specific zones) but cannot lower the national minimums.

The Office of the Building Official (OBO) is the local enforcement arm. The OBO issues building permits, conducts inspections, issues occupancy certificates, and has authority to stop work on non-compliant construction.

**The permit sequence every architect must know:**

1. Building Permit (OBO) — before construction begins
2. Fire Safety Evaluation Clearance (BFP) — before building permit is issued
3. Electrical Permit, Sanitary/Plumbing Permit, Mechanical Permit — separate allied permits
4. Certificate of Occupancy (OBO) — before building is occupied
5. Fire Safety Inspection Certificate (BFP) — before occupancy

<Note>The Fire Safety Evaluation Clearance from the BFP is a prerequisite for the building permit — not a parallel process. Many examinees miss this sequencing. RA 9514 requires BFP clearance before OBO can issue the building permit for covered occupancies.</Note>

## The Planning Laws Chain: From National to Site

**RA 7160 (Local Government Code) → Comprehensive Land Use Plan (CLUP) → Zoning Ordinance → Site Development Permit → Subdivision Development (PD 957 / BP 220)**

RA 7160 devolved land use planning authority to LGUs. Each LGU is required to prepare a Comprehensive Land Use Plan (CLUP) — the master document for how land in the jurisdiction is classified and used. The CLUP is operationalized through the local Zoning Ordinance, which determines what can be built where.

For residential development, PD 957 governs subdivision and condominium development by private developers — registration requirements, mandatory community facilities, buyer protections. BP 220 sets the minimum design standards for economic and socialized housing subdivisions, overriding the more generous PD 957 standards for projects serving lower-income households.

